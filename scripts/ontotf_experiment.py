from __future__ import annotations

import argparse
import gc
import hashlib
import os
import subprocess
from dataclasses import replace
from importlib.metadata import version
from pathlib import Path
from typing import Any

from tf.fabric import Fabric

from scripts.diagnose_abstention import TraceBackend, _write, verify_sources
from scripts.measure_comparison import RecordingParser
from scripts.nl_benchmark_v2 import execute, load_benchmark
from scripts.ontotf_context import OntologyBackend, load_catalog
